package routes

import (
	"github.com/gin-gonic/gin"
	"github.com/ngwebwork/payflow/internal/handlers"
	"github.com/ngwebwork/payflow/internal/middleware"
	"github.com/ngwebwork/payflow/internal/services"
)

func Setup(r *gin.Engine, h *handlers.AuthHandler, dashboard *handlers.DashboardHandler, resources *handlers.ResourceHandler, customers *handlers.CustomerHandler, settings *handlers.SettingsHandler, payments *handlers.PaymentHandler, invoices *handlers.InvoiceHandler, subscriptions *handlers.SubscriptionHandler, analytics *handlers.AnalyticsHandler, notifications *handlers.NotificationHandler, transfers *handlers.TransferHandler, chat *handlers.ChatHandler, jwt *services.JWTService, clientURL string) {
	r.Use(middleware.CORS(clientURL))
	// Render probes the service root. Keep this public and dependency-free so a
	// successful deployment is distinguishable from an unknown API path.
	r.GET("/", func(c *gin.Context) {
		c.JSON(200, gin.H{"status": "ok"})
	})
	r.GET("/healthz", func(c *gin.Context) {
		c.JSON(200, gin.H{"status": "ok"})
	})
	api := r.Group("/api/v1/auth")
	api.POST("/signup", h.Signup)
	api.POST("/login", h.Login)
	api.POST("/refresh", h.Refresh)
	api.POST("/forgot-password", h.ForgotPassword)
	api.POST("/reset-password", h.ResetPassword)
	api.POST("/verify-email", h.VerifyEmail)
	api.POST("/resend-email-verification", h.ResendEmail)
	protected := api.Group("")
	protected.Use(middleware.Auth(jwt))
	protected.POST("/logout", h.Logout)
	protected.GET("/me", h.Me)
	protected.POST("/send-phone-code", h.SendPhone)
	protected.POST("/resend-phone-code", h.ResendPhone)
	protected.POST("/verify-phone", h.VerifyPhone)
	dashboardAPI := r.Group("/api/v1/dashboard")
	dashboardAPI.Use(middleware.Auth(jwt))
	dashboardAPI.GET("/summary", dashboard.Summary)
	dashboardAPI.GET("/revenue", dashboard.Revenue)
	dashboardAPI.GET("/transactions", dashboard.Transactions)
	dashboardAPI.GET("/customers", dashboard.Customers)
	analyticsAPI := r.Group("/api/v1/analytics")
	analyticsAPI.Use(middleware.Auth(jwt))
	analyticsAPI.GET("/summary", analytics.Summary)
	analyticsAPI.GET("/revenue", analytics.Revenue)
	analyticsAPI.GET("/transactions", analytics.Transactions)
	analyticsAPI.GET("/customers", analytics.Customers)
	analyticsAPI.GET("/payments", analytics.Payments)
	customersAPI := r.Group("/api/v1/customers")
	customersAPI.Use(middleware.Auth(jwt))
	customersAPI.GET("", customers.List)
	customersAPI.POST("", customers.Create)
	customersAPI.GET("/:id", customers.Get)
	customersAPI.PUT("/:id", customers.Update)
	customersAPI.DELETE("/:id", customers.Delete)
	customersAPI.GET("/:id/payments", customers.Payments)
	customersAPI.GET("/:id/transactions", customers.Transactions)
	paymentsAPI := r.Group("/api/v1/payments")
	paymentsAPI.POST("/webhook", payments.Webhook)
	paymentsAPI.Use(middleware.Auth(jwt))
	paymentsAPI.POST("/initialize", payments.Initialize)
	paymentsAPI.GET("/verify/:reference", payments.Verify)
	paymentsAPI.GET("/summary", payments.Summary)
	paymentsAPI.GET("", payments.List)
	paymentsAPI.GET("/:id", payments.Get)
	invoicesAPI := r.Group("/api/v1/invoices")
	invoicesAPI.Use(middleware.Auth(jwt))
	invoicesAPI.GET("", invoices.List)
	invoicesAPI.POST("", invoices.Create)
	invoicesAPI.GET("/:id", invoices.Get)
	invoicesAPI.PUT("/:id", invoices.Update)
	invoicesAPI.DELETE("/:id", invoices.Delete)
	invoicesAPI.POST("/:id/send", invoices.Send)
	invoicesAPI.POST("/:id/mark-paid", invoices.MarkPaid)
	subscriptionsAPI := r.Group("/api/v1/subscriptions")
	subscriptionsAPI.Use(middleware.Auth(jwt))
	subscriptionsAPI.GET("", subscriptions.List)
	subscriptionsAPI.GET("/summary", subscriptions.Summary)
	subscriptionsAPI.POST("", subscriptions.Create)
	subscriptionsAPI.GET("/:id", subscriptions.Get)
	subscriptionsAPI.PUT("/:id", subscriptions.Update)
	subscriptionsAPI.POST("/:id/cancel", subscriptions.Cancel)
	// Transactions are a read-only projection of verified payments: they must only ever be
	// written by PaymentRepository.MarkSuccessful (after server-side Paystack verification),
	// never accepted as arbitrary client input, so only read routes are exposed here.
	for _, collection := range []string{"transactions"} {
		resourceAPI := r.Group("/api/v1/" + collection)
		resourceAPI.Use(middleware.Auth(jwt))
		resourceAPI.GET("", func(c *gin.Context) {
			c.Params = append(c.Params, gin.Param{Key: "resource", Value: collection})
			resources.List(c)
		})
		resourceAPI.GET("/:id", func(c *gin.Context) {
			c.Params = append(c.Params, gin.Param{Key: "resource", Value: collection})
			resources.Get(c)
		})
	}
	settingsAPI := r.Group("/api/v1/settings")
	settingsAPI.Use(middleware.Auth(jwt))
	settingsAPI.GET("/profile", settings.Profile)
	settingsAPI.PUT("/profile", settings.UpdateProfile)
	settingsAPI.GET("/business", settings.Business)
	settingsAPI.PUT("/business", settings.UpdateBusiness)
	settingsAPI.GET("/notifications", settings.Notifications)
	settingsAPI.PUT("/notifications", settings.UpdateNotifications)
	settingsAPI.POST("/change-password", settings.ChangePassword)

	notificationsAPI := r.Group("/api/v1/notifications")
	notificationsAPI.Use(middleware.Auth(jwt))
	notificationsAPI.GET("", notifications.List)
	notificationsAPI.GET("/unread-count", notifications.UnreadCount)
	notificationsAPI.POST("/:id/read", notifications.MarkRead)
	notificationsAPI.POST("/read-all", notifications.MarkAllRead)

	walletAPI := r.Group("/api/v1/wallet")
	walletAPI.Use(middleware.Auth(jwt))
	walletAPI.GET("/balance", transfers.Balance)

	transfersAPI := r.Group("/api/v1/transfers")
	transfersAPI.Use(middleware.Auth(jwt))
	transfersAPI.POST("", transfers.Send)
	transfersAPI.GET("", transfers.List)

	chatAPI := r.Group("/api/v1/chat")
	chatAPI.Use(middleware.Auth(jwt))
	chatAPI.GET("/users", chat.SearchUsers)
	chatAPI.POST("/conversations", chat.StartConversation)
	chatAPI.GET("/conversations", chat.ListConversations)
	chatAPI.GET("/conversations/:id/messages", chat.Messages)
	chatAPI.POST("/conversations/:id/messages", chat.SendMessage)
	chatAPI.POST("/conversations/:id/read", chat.MarkRead)
	chatAPI.GET("/unread-count", chat.UnreadCount)
	// The websocket handshake authenticates the access token itself (see ChatHandler.Socket)
	// since browsers cannot attach an Authorization header to a WebSocket upgrade request.
	r.GET("/api/v1/ws", chat.Socket)
}
